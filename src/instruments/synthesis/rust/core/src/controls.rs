#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn legacy_parameters_recover_original_physical_values() {
        for i in 0..=100 {
            let old = i as f32 / 100.0;
            let p = migrate_legacy_parameter(6, 0, old);
            assert!((1.0 + 499.0 * p - (8.0 + 192.0 * old)).abs() < 0.0001);
            let p = migrate_legacy_parameter(11, 0, old);
            assert!((0.0625 + 31.9375 * p - (0.1 + 11.9 * old)).abs() < 0.00001);
            let p = migrate_legacy_parameter(7, 0, old);
            let ratio = 20.0 * 1000.0f32.powf(p) / (80.0 * 200.0f32.powf(old));
            assert!((ratio - 1.0).abs() < 0.00001);
            let p = migrate_legacy_parameter(21, 1, old);
            assert_eq!((p * 31.0 + 0.00001).floor(), (old * 7.0).floor());
            let p = migrate_legacy_parameter(15, 2, old);
            assert_eq!((p * 255.0 + 0.00001).floor(), (old * 47.0).floor());
        }
        assert_eq!(migrate_legacy_parameter(2, 7, 0.3), 0.3);
        assert!(migrate_legacy_parameter(11, 0, f32::NAN).is_finite());
    }
}
