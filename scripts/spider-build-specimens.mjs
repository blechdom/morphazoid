import { readFile, writeFile } from 'node:fs/promises';

// Small rig descriptions load with the sound engine; specimen GLBs remain lazy.
// Run after authoring an asset. --partial permits local work on unfinished rigs.
const partial = process.argv.includes('--partial');
const entries = [
  ['argiope', 'Wasp spider', '', 'An orb-weaver; the original Argiope bruennichi scan.', 'CC0'],
  ['golden', 'Golden orb-weaver', 'skins/golden/', 'A long-legged orb-weaver with a gold-patterned abdomen.', 'CC0'],
  ['devil', 'Devil orb-weaver', 'skins/devil/', 'A round-bodied Araneus orb-weaver.', 'CC0'],
  ['tarantula', 'King baboon tarantula', 'skins/tarantula/', 'A burrowing tarantula. Try Funnel or Sheet for a silk-retreat performance.', 'CC BY 4.0 · Auckland Museum'],
  ['huntsman', 'Huntsman', 'skins/huntsman/', 'A hunting spider with sideways-spreading legs; the musical web is an artistic setting.', 'CC0'],
  ['fishing', 'Fishing spider', 'skins/fishing/', 'A striped hunting spider. The source species identification is provisional.', 'CC0'],
];
const records = [];
for (const [id, label, directory, description, credit] of entries) {
  const base = `../assets/spider-synth/${directory}`;
  let rig;
  try { rig = JSON.parse(await readFile(new URL(`${base}rig-manifest.json`, import.meta.url))); }
  catch (error) { if (partial && error.code === 'ENOENT') continue; throw error; }
  if (rig.joints?.length !== 38 || rig.legs?.length !== 8) throw new Error(`Invalid ${id} specimen rig`);
  records.push({ id, label, description, credit, species: rig.species,
    modelPath: `${base}spider-mobile.glb`, rigPath: `${base}rig-manifest.json`,
    rig: { version: rig.version, species: rig.species, bodyLength: rig.bodyLength,
      bodyHeight: rig.neutralBodyHeight ?? rig.bodyHeight, collision: rig.collision,
      joints: rig.joints.map(({ id, parent, pivot }) => ({ id, parent, pivot })),
      legs: rig.legs.map(({ id, jointIds, anchors, lengths, radii }) => ({ id, jointIds, anchors, lengths, radii })) } });
}
const output = '// Generated by scripts/spider-build-specimens.mjs from the authored scan rigs.\n'
  + `export const SPIDER_SPECIMEN_DATA = ${JSON.stringify(records)};\n`;
await writeFile(new URL('../src/spider-synth-specimen-data.js', import.meta.url), output);
console.log(`Prepared ${records.length} specimen profiles (${Buffer.byteLength(output)} bytes); no models are preloaded.`);
