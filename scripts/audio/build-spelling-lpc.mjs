// Deterministic, original LPC analysis of Morphazoid's licensed Flite KAL atlas.
// Run from any directory: node scripts/audio/build-spelling-lpc.mjs [--check]
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {SPELLING_DIPHONE_ATLAS_URL, SPELLING_DIPHONE_CLIPS} from '../../src/instruments/spelling-synthesizer/spelling-diphone-atlas.js';
import {analyseLpcFrame, LPC_FRAME} from '../../src/instruments/spelling-synthesizer/spelling-lpc-codec.js';
const bytes = readFileSync(SPELLING_DIPHONE_ATLAS_URL);
let pcm, rate, channels, bits;
for (let p = 12; p + 8 <= bytes.length;) {
  const tag = bytes.toString('ascii', p, p+4), size = bytes.readUInt32LE(p+4);
  if (tag === 'fmt ') { if(bytes.readUInt16LE(p+8)!==1) throw Error('PCM required'); channels=bytes.readUInt16LE(p+10);rate=bytes.readUInt32LE(p+12);bits=bytes.readUInt16LE(p+22); }
  if (tag === 'data') pcm = bytes.subarray(p+8, p+8+size);
  p += 8 + size + (size & 1);
}
if(rate!==16000 || channels!==1 || bits!==16 || !pcm) throw Error('Expected the unchanged mono 16kHz KAL16 atlas');
const source = Float64Array.from({length:pcm.length/2},(_,i)=>pcm.readInt16LE(i*2)/32768);
// Windowed-sinc anti-alias filter before 2:1 decimation; no browser decode variance.
const taps = Array.from({length:63},(_,i)=> {const n=i-31;return (n ? Math.sin(2*Math.PI*.225*n)/(Math.PI*n) : .45) * (.54-.46*Math.cos(2*Math.PI*i/62));});
const sum = taps.reduce((a,b)=>a+b,0);for(let i=0;i<taps.length;i++)taps[i]/=sum;
const atlas = {};
for (const [key, clip] of Object.entries(SPELLING_DIPHONE_CLIPS)) {
  const start=Math.round(clip.offset*16000), length=Math.ceil(clip.duration*8000);
  const signal=new Float64Array(length);
  for(let i=0;i<length;i++)for(let j=0;j<taps.length;j++)signal[i]+=(source[start+i*2+j-31]??0)*taps[j];
  const frames=[];
  for(let i=0;i<length;i+=LPC_FRAME) {
    const frame=Float64Array.from({length:320},(_,n)=>signal[Math.max(0,Math.min(length-1,i+n-60))]);
    frames.push(analyseLpcFrame(frame));
  }
  atlas[key]={frames,hold:Math.max(0,Math.floor(((clip.sustainStart+clip.sustainEnd)/2 || clip.duration*.55)*40)),duration:clip.duration};
}
const result='// Generated by scripts/audio/build-spelling-lpc.mjs; do not hand edit.\n// Derived from CMU Flite KAL16; see THIRD_PARTY_NOTICES.md. No TI ROM data.\n'
 +`export const LPC_SOURCE_SHA256 = ${JSON.stringify(createHash('sha256').update(bytes).digest('hex'))};\n`
 +`export const SPELLING_LPC_ATLAS = Object.freeze(${JSON.stringify(atlas)});\n`;
const target=new URL('../../src/instruments/spelling-synthesizer/spelling-lpc-atlas.js',import.meta.url);
if(process.argv.includes('--check')) {if(readFileSync(target,'utf8')!==result)throw Error('LPC atlas differs; regenerate it');}
else writeFileSync(target,result);
console.log(`${Object.keys(atlas).length} LPC phones/pairs; ${result.length} bytes`);
