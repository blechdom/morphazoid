import { readFile, writeFile, mkdir, rename, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Worker } from 'node:worker_threads';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Rebuild the zero-latency whole-instrument factory cache using the *production*
// Worker, scheduler and WASM. This never imports the runtime matcher/cache.
//   node scripts/calibrate-synthesis-performance-levels.mjs
// To review without replacing source:
//   node scripts/calibrate-synthesis-performance-levels.mjs --output /tmp/factories.js --report /tmp/factory-levels.json
// This is dry-source calibration, not a mastering/LUFS or listening approval.
const DEFAULT_ROOT = fileURLToPath(new URL('../', import.meta.url));
const CACHE_PATH = 'src/instruments/synthesis/performance-level-factories.js';
const WORKER_PATH = 'src/instruments/synthesis/performance-level-worker.js';
const WASM_PATH = 'assets/wasm/synthesis.wasm';
const SOURCE_PATHS = [
  'catalog.js', 'instrument-presets.js', 'percussion-state.js', 'performance-level-worker.js',
  'performance-level-measure.js', 'processor.js', 'sequence-catalog.js',
  'sequence-compiler.js', 'sequence-parameters.js', 'sequence-register.js', 'tunings.js',
].map(file => `src/instruments/synthesis/${file}`);
const hash = value => createHash('sha256').update(value).digest('hex');

export function parseOptions(args) {
  const values = {};
  const known = new Set(['--root', '--output', '--report', '--sample-rate']);
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--help') return { help: true };
    if (!known.has(args[i])) throw new Error(`Unknown option: ${args[i]}`);
    if (args[i + 1] === undefined || args[i + 1].startsWith('--')) throw new Error(`Missing value for ${args[i]}`);
    values[args[i].slice(2)] = args[++i];
  }
  const root = resolve(values.root || DEFAULT_ROOT);
  const sampleRate = Number(values['sample-rate'] ?? 48000);
  if (!Number.isInteger(sampleRate) || sampleRate < 8000 || sampleRate > 192000) throw new Error('Sample rate must be an integer from 8000 to 192000.');
  return { root, sampleRate, output: resolve(values.output || resolve(root, CACHE_PATH)),
    report: values.report ? resolve(values.report) : null };
}

export function canonicalPerformance(value) {
  if (Array.isArray(value)) return value.map(canonicalPerformance);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value)
    .filter(key => key !== 'outputLevel').sort().map(key => [key, canonicalPerformance(value[key])]));
  return value;
}

export function buildFactoryModule(rows, metadata) {
  const entries = rows.map(({ snapshot, result }) => {
    const matched = structuredClone(result);
    delete matched.stats.reference;
    matched.stats.calibration = 'factory';
    return [JSON.stringify(canonicalPerformance(snapshot)), matched];
  });
  if (new Set(entries.map(([key]) => key)).size !== entries.length) throw new Error('Duplicate complete factory snapshots need explicit deduplication.');
  const info = { ...metadata,
    snapshotsSha256: hash(entries.map(([key]) => key).sort().join('\n')),
    sceneCount: entries.length };
  return `// Generated by: node scripts/calibrate-synthesis-performance-levels.mjs
// Actual production worklet/WASM dry whole-phrase renders; not a runtime AGC.
// Exact snapshot keys avoid stale reuse after any musical edit. Source hashes
// record provenance; refresh measurements after behavior changes, not comments.
export const FACTORY_LEVEL_MATCH_META = Object.freeze(${JSON.stringify(info, null, 2)});

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value)
    .filter(key => key !== 'outputLevel').sort().map(key => [key, canonical(value[key])]));
  return value;
}

export function performanceLevelKey(performance) {
  return JSON.stringify(canonical(performance));
}

const measured = new Map([
${entries.map(entry => '  ' + JSON.stringify(entry)).join(',\n')}
]);

/** Immediate recall for measured factories; other rates/edits use background measurement. */
export function factoryLevelMatch(performance, { sampleRate = 48000 } = {}) {
  if (sampleRate !== FACTORY_LEVEL_MATCH_META.sampleRate) return null;
  const result = measured.get(performanceLevelKey(performance));
  return result ? structuredClone(result) : null;
}
`;
}

function makeWorker(root) {
  const url = pathToFileURL(resolve(root, WORKER_PATH)).href;
  const worker = new Worker(`
    const { parentPort } = require('node:worker_threads');
    const { readFile } = require('node:fs/promises');
    let listener;
    const queued = [];
    globalThis.postMessage = data => parentPort.postMessage(data);
    globalThis.addEventListener = (name, fn) => {
      if (name === 'message') { listener = fn; for (const data of queued.splice(0)) listener({ data }); }
    };
    parentPort.on('message', data => listener ? listener({ data }) : queued.push(data));
    globalThis.fetch = async url => {
      if (url.protocol !== 'file:') throw new Error('Offline calibration only reads local engine assets.');
      return new Response(await readFile(url));
    };
    import(${JSON.stringify(url)}).catch(error => { throw error; });
  `, { eval: true });
  let pending = null;
  const settle = (error, data) => {
    if (!pending) return;
    const request = pending; pending = null; clearTimeout(request.timer);
    if (error) request.reject(error); else request.resolve(data);
  };
  worker.on('message', data => {
    if (!pending || data.id != null && data.id !== pending.id) return;
    if (data.type === 'error') settle(new Error(data.message || 'Offline level worker failed.'));
    else if (data.type === 'ready' || data.type === 'result') settle(null, data.result);
  });
  worker.on('error', error => settle(error));
  worker.on('exit', code => { if (pending) settle(new Error(`Offline level worker exited during measurement (${code}).`)); });
  return {
    send(message) {
      if (pending) throw new Error('Level measurements must be serialized.');
      return new Promise((resolve, reject) => {
        pending = { id: message.id, resolve, reject,
          timer: setTimeout(() => settle(new Error('Offline level measurement timed out.')), 60000) };
        worker.postMessage(message);
      });
    },
    async dispose() { settle(new Error('Offline level worker closed.')); await worker.terminate(); },
  };
}

async function fingerprint(root) {
  const files = [WASM_PATH, ...SOURCE_PATHS];
  return Object.fromEntries(await Promise.all(files.map(async path => [path, hash(await readFile(resolve(root, path)))])));
}

async function atomicWrite(path, text) {
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.calibrating-${process.pid}`;
  try { await writeFile(temporary, text, { flag: 'wx' }); await rename(temporary, path); }
  catch (error) {
    if (error.code !== 'EEXIST') await unlink(temporary).catch(() => {});
    throw error;
  }
}

export async function calibrate(options) {
  const { root, sampleRate, output, report } = options;
  const before = await fingerprint(root);
  const { INSTRUMENT_PRESETS } = await import(pathToFileURL(resolve(root, 'src/instruments/synthesis/instrument-presets.js')));
  const scenes = INSTRUMENT_PRESETS.filter(preset => ['synthesis', 'percussion'].includes(preset.snapshot.routing.input));
  if (!scenes.length) throw new Error('No synthesis/percussion factory scenes found.');
  const worker = makeWorker(root), rows = [];
  const started = performance.now();
  try {
    await worker.send({ type: 'warm' });
    for (let index = 0; index < scenes.length; index++) {
      const scene = scenes[index], start = performance.now();
      let result;
      try { result = await worker.send({ type: 'match', id: index + 1, performance: scene.snapshot, sampleRate }); }
      catch (error) { throw new Error(`${scene.id}: ${error.message}`, { cause: error }); }
      if (result.stats.silent || result.stats.nonfinite || result.stats.skipped
        || !(result.outputGain > 0 && result.outputGain <= 16)
        || !(result.stats.peak * result.outputGain <= .7)
        || !Number.isFinite(result.stats.scoreDb)
        || result.stats.scoreDb + 20 * Math.log10(result.outputGain) > -15
        || scene.snapshot.routing.input === 'synthesis'
          && !(Number.isFinite(result.sourceTrimDb) && result.sourceTrimDb >= -36 && result.sourceTrimDb <= 48)) {
        throw new Error(`${scene.id}: refusing to cache a silent, skipped or unsafe result.`);
      }
      rows.push({ id: scene.id, snapshot: scene.snapshot, result, durationMs: performance.now() - start });
      process.stderr.write(`${index + 1}/${scenes.length} ${scene.id}\n`);
    }
  } finally { await worker.dispose(); }
  const after = await fingerprint(root);
  if (JSON.stringify(before) !== JSON.stringify(after)) throw new Error('Calibration source changed during rendering; no output was replaced. Retry on stable source.');
  const metadata = { version: 1, sampleRate, targetDb: -15, safetyDb: 1.5, peakLimit: .7,
    wasmSha256: before[WASM_PATH],
    sourceHashes: Object.fromEntries(SOURCE_PATHS.map(path => [path, before[path]])),
    measuredAt: new Date().toISOString(), score: 'max(K-weighted 400 ms RMS, K-weighted 100 ms RMS - 3 dB)',
    scope: 'Dry source; exact complete musical snapshots. Not integrated LUFS or true peak.' };
  const source = buildFactoryModule(rows, metadata);
  if (report) await atomicWrite(report, JSON.stringify({ root, metadata, durationMs: performance.now() - started, rows }, null, 2) + '\n');
  await atomicWrite(output, source);
  process.stderr.write(`Measured ${rows.length} factories at ${sampleRate} Hz; wrote ${output}. No listening approval is implied.\n`);
  return { rows, metadata };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = parseOptions(process.argv.slice(2));
  if (options.help) console.log('Options: --root DIR --output FILE --report FILE --sample-rate 48000\nDefault output: src/instruments/synthesis/performance-level-factories.js in the selected root. All factories are rendered; no runtime cache is used.');
  else await calibrate(options);
}
